function getDistanceToBiz(bizId)
    local id = tonumber(bizId)
    if not id then return nil end

    local coord = nil

    for i = 1, #coordbiz do
        if tonumber(coordbiz[i][4]) == id then
            coord = coordbiz[i]
            break
        end
    end

    if not coord then return nil end

    local px, py, pz = getCharCoordinates(PLAYER_PED)
    local cx, cy, cz = coord[1], coord[2], coord[3]

    return math.floor(math.sqrt((px - cx)^2 + (py - cy)^2 + (pz - cz)^2))
end

