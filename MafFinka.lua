    end
end

function Draw3DCircle(x, y, z, radius, color, width, segments) -- 3d круг
    color = color or 0xFFD00000
    width = width or 2.0
    segments = segments or 24

    local firstX, firstY = nil, nil
    local prevX, prevY = nil, nil

    for i = 0, segments do
        local angle = (i / segments) * 2 * math.pi

        local px = x + radius * math.cos(angle)
        local py = y + radius * math.sin(angle)
        local pz = z + 0.3 -- чуть над землёй

        local ok, sx, sy = convert3DCoordsToScreenEx(px, py, pz, true, true)

        if ok then
            -- сохраняем первую точку
            if not firstX then
                firstX, firstY = sx, sy
            end

            -- рисуем линию
            if prevX then
                renderDrawLine(prevX, prevY, sx, sy, width, color)
            end

            prevX, prevY = sx, sy
        end
    end

    -- правильное замыкание круга
    if prevX and firstX then
        renderDrawLine(prevX, prevY, firstX, firstY, width, color)
    end
end

function addignorelist(args) -- Добавить в игнор лист

    -- Если аргументов нет — очищаем весь список
    if not args or args == '' then
        message('Команда используется в формате /addignorebiz id')
        return
    end

    -- Обрабатываем аргумент как ID бизнеса
    local targetId = tonumber(args)

    -- Проверка: корректен ли ID (число)
    if not targetId then
        message('Ошибка: укажите корректный ID бизнеса (число)')
        return
    end

    -- Поиск ID в игнор?списке
    local foundIndex = nil
    for i, id in ipairs(settings.ignoreBizIds) do
        if id == targetId then
            foundIndex = i
            break
        end
    end

    -- Если ID не найден
    if foundIndex then
        message(string.format('Бизнес с ID %d найден в игнор листе, второй раз добавлять не буду...', targetId))
        return
    end

    -- Удаление найденного ID из списка
    table.insert(settings.ignoreBizIds, targetId)
    save_settings()
    message(string.format('Бизнес с ID %d успешно добавлен в игнор лист', targetId))

end

