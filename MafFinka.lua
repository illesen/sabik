function honkController()
    local HONK_DISTANCE = settings.takefinka.radiusHonk
    local HONK_DISTANCE_SQ = HONK_DISTANCE * HONK_DISTANCE

    if not settings or not settings.Finka then return end
    if not isCharInAnyCar(PLAYER_PED) then

        isHonkActive = false
        currentBizId = nil

        return
    end

    local px, py, pz = getCharCoordinates(PLAYER_PED)
    if not px then return end

    local closestBiz = nil
    local closestDistSq = HONK_DISTANCE_SQ

    for _, biz in ipairs(settings.Finka) do

        local coord = coordById[tostring(biz.idbiz)]

        if coord and not isIgnored(biz.idbiz) then

            local dx = coord.x - px
            local dy = coord.y - py
            local dz = coord.z - pz

            local distSq = dx*dx + dy*dy + dz*dz

            if distSq < closestDistSq then
                closestDistSq = distSq
                closestBiz = biz
            end
        end
    end

    if not closestBiz or closestDistSq > HONK_DISTANCE_SQ then

        isHonkActive = false
        currentBizId = nil

        return
    end

    if currentBizId ~= closestBiz.idbiz then
        currentBizId = closestBiz.idbiz
    end

    if not isHonkActive then

        isHonkActive = true

        honkThread = lua_thread.create(function()

            while isHonkActive do

                -- сам флуд
                for i = 1, settings.takefinka.quantityHonk do

                    if not isHonkActive then break end

                    honk()
                    wait(settings.takefinka.cbb)

                end

                wait(settings.takefinka.cbc)

            end

        end)

    end
end

function drawFinkaOnScreen()
    if not settings.render then return end

    local px, py, pz = getCharCoordinates(PLAYER_PED)
    if not px then return end

    local minMoney = settings.min_money or 0
    local maxDist = settings.max_dist_render or 200
    local maxDistSq = maxDist * maxDist

    for _, biz in ipairs(settings.Finka) do

        if isIgnored(biz.idbiz) then
            goto continue
        end

        local money = biz.cash

        if money >= minMoney then

            local coord = coordById[tostring(biz.idbiz)]
            if coord then

                local dx = coord.x - px
                local dy = coord.y - py
                local dz = coord.z - pz

                local distSq = dx*dx + dy*dy + dz*dz

                if distSq <= maxDistSq then

                    local ok, sx, sy = convert3DCoordsToScreenEx(coord.x, coord.y, coord.z, true, true)

                    if ok then

                        if not isInFOV(sx, sy, 0.45) then
                            goto continue
                        end

                        local dist = math.sqrt(distSq)

                        local color = 0xFFFF0000
                        if money > 800000 then
                            color = 0xFF00FF00
                        elseif money > 200000 then
                            color = 0xFFFFFF00
                        end

                        if settings.render_circle and distSq < 40000 then
                            Draw3DCircle(coord.x, coord.y, coord.z - 2, 12, color, 2.5, 30)
                        end

                        local an, rn, gn, bn = explode_argb(settings.color.colornumberbiz)
                        local ad, rd, gd, bd = explode_argb(settings.color.colordistbiz)
                        local am, rm, gm, bm = explode_argb(settings.color.colormoneybiz)
                        local numb = tostring(string.format("%02X%02X%02X", rn, gn, bn))
                        local distcolor = tostring(string.format("%02X%02X%02X", rd, gd, bd))
                        local moneycolor = tostring(string.format("%02X%02X%02X", rm, gm, bm))

                        renderFontDrawTextAlign(
                            font,
                            ('[{%s}%s{ffffff}] %s'):format(numb, biz.idbiz, biz.name_biz),
                            sx, sy,
                            0xFFFFFFFF,
                            2
                        )

                        renderFontDrawTextAlign(
                            font,
                            string.format('{%s}%.0f м {ffffff}| {%s}%s', distcolor, dist, moneycolor, formatNumberWithDots(money)),
                            sx, sy + 20,
                            0xFFFFFFFF,
                            2
                        )
                    end
                end
            end
        end

        ::continue::
    end
end

